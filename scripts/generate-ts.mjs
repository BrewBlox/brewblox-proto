// protobufjs only honours `option allow_alias = true` for values parsed after
// it, while protoc accepts it anywhere in the enum body.
function hoistAllowAlias(src) {
  return src.replace(/enum\s+\w+\s*\{[^}]*\}/g, (body) => {
    if (!/option\s+allow_alias\s*=\s*true\s*;/.test(body)) {
      return body;
    }
    const stripped = body.replace(
      /\s*option\s+allow_alias\s*=\s*true\s*;/g,
      '',
    );
    return stripped.replace('{', '{\n  option allow_alias = true;');
  });
}

async function loadRoot() {
  const root = new protobuf.Root();
  // Every import in the set is a bare filename.
  root.resolvePath = (origin, target) =>
    target.startsWith('google/')
      ? target
      : path.join(protoDir, path.basename(target));
  // The callback must be asynchronous: a synchronous callback makes protobufjs
  // finish after the first nested import and silently drop the rest.
  root.fetch = (filename, cb) => {
    setImmediate(() => {
      if (filename === 'google/protobuf/descriptor.proto') {
        cb(null, DESCRIPTOR_STUB);
        return;
      }
      try {
        cb(null, hoistAllowAlias(fs.readFileSync(filename, 'utf8')));
      } catch (e) {
        cb(e);
      }
    });
  };
  const files = fs
    .readdirSync(protoDir)
    .filter((f) => f.endsWith('.proto'))
    .sort()
    .map((f) => path.join(protoDir, f));
  // keepCase: the service decodes with preserving_proto_field_name, so
  // `spec_r0` must stay `spec_r0`.
  await root.load(files, {
    keepCase: true,
    alternateCommentMode: true,
    preferTrailingComment: true,
  });
  root.resolveAll();
  return root;
}

