class Generator {
  constructor(root) {
    this.root = root;
    this.blockTypeEnum = root.lookupEnum('brewblox.BlockType');
    this.messages = new Map(); // fq -> Type, reachable
    this.enums = new Map(); // fq -> Enum, referenced by a field
    this.owners = new Map(); // fq -> Set<objtype>
    this.blocks = []; // { type, objtype, impl }
    this.messageNames = new Map(); // fq -> TS name
    this.enumNames = new Map(); // fq -> TS name
    this.regionOrder = new Map(); // region -> [fq...] in emission order
  }

  // --- names ---------------------------------------------------------------

  messageName(type) {
    const name = fq(type);
    if (this.messageNames.has(name)) {
      return this.messageNames.get(name);
    }
    const opts = msgOpts(type);
    const tsName =
      MESSAGE_RENAMES[name] ??
      (opts.objtype ? `${opts.objtype}Block` : type.name);
    for (const [other, otherName] of this.messageNames) {
      if (otherName === tsName) {
        fail(`TS name collision: ${name} and ${other} both map to ${tsName}`);
      }
    }
    this.messageNames.set(name, tsName);
    return tsName;
  }

  enumName(enm) {
    const name = fq(enm);
    if (!this.enumNames.has(name)) {
      const tsName = ENUM_RENAMES[name] ?? enm.name;
      for (const [other, otherName] of this.enumNames) {
        if (otherName === tsName) {
          fail(`TS name collision: ${name} and ${other} both map to ${tsName}`);
        }
      }
      this.enumNames.set(name, tsName);
    }
    return this.enumNames.get(name);
  }

  // --- reachability --------------------------------------------------------

  collect() {
    const blox = this.root.lookup('blox');
    for (const obj of walk(blox)) {
      if (!isType(obj)) {
        continue;
      }
      const opts = msgOpts(obj);
      if (opts.subtype !== undefined) {
        continue; // test-only messages
      }
      if (!opts.objtype) {
        continue;
      }
      const members = enumMembers(this.blockTypeEnum);
      if (!members.some((m) => m.name === opts.objtype)) {
        warn(
          `${fq(obj)}: objtype ${opts.objtype} is an alias; ` +
            'the service emits the first name for its value',
        );
      }
      this.blocks.push({ type: obj, objtype: opts.objtype, impl: opts.impl });
    }
    this.blocks.sort((a, b) => cmpName(a.objtype, b.objtype));
    const seenObjtypes = new Set();
    for (const block of this.blocks) {
      if (seenObjtypes.has(block.objtype)) {
        fail(`objtype ${block.objtype} is used by more than one Block message`);
      }
      seenObjtypes.add(block.objtype);
      this.visit(block.type, block.objtype, new Set());
    }
  }

  visit(type, owner, stack) {
    const name = fq(type);
    if (!name.startsWith('blox.')) {
      fail(`${name} is outside the blox package`);
    }
    if (Object.keys(type.nested ?? {}).length) {
      fail(
        `${name} has nested declarations; the generator does not flatten them`,
      );
    }
    this.messages.set(name, type);
    if (!this.owners.has(name)) {
      this.owners.set(name, new Set());
    }
    this.owners.get(name).add(owner);
    if (stack.has(name)) {
      return;
    }
    stack.add(name);
    for (const field of this.emittedFields(type)) {
      const target = (wrappedItems(field) ?? field).resolvedType;
      if (!target || FIELD_TYPE_OVERRIDES[`${name}.${field.name}`]) {
        continue;
      }
      if (isEnum(target)) {
        this.enums.set(fq(target), target);
      } else {
        this.visit(target, owner, stack);
      }
    }
    stack.delete(name);
  }

  emittedFields(type) {
    const name = fq(type);
    return type.fieldsArray.filter((field) => {
      const opts = fieldOpts(field);
      if (opts.ignored || opts.ftIgnore) {
        return false;
      }
      if (SKIPPED_FIELDS.has(`${name}.${field.name}`)) {
        return false;
      }
      return true;
    });
  }

  // --- regions -------------------------------------------------------------

  assignRegions() {
    const placed = new Map(); // fq -> region
    for (const shared of SHARED_REGIONS) {
      for (const name of shared.messages ?? []) {
        if (!this.messages.has(name)) {
          fail(
            `SHARED_REGIONS lists ${name}, which is not reachable from any Block`,
          );
        }
        placed.set(name, shared.region);
      }
    }
    for (const [name, owners] of this.owners) {
      if (placed.has(name)) {
        continue;
      }
      if (owners.size !== 1) {
        fail(
          `${name} is referenced by ${[...owners].join(', ')}; ` +
            'add it to SHARED_REGIONS',
        );
      }
      placed.set(name, [...owners][0]);
    }
    this.regions = placed;
  }

  // Helper messages of a block, dependencies first, in field order.
  blockRegionMessages(block) {
    const out = [];
    const seen = new Set();
    const dfs = (type) => {
      const name = fq(type);
      if (seen.has(name)) {
        return;
      }
      seen.add(name);
      for (const field of this.emittedFields(type)) {
        const target = (wrappedItems(field) ?? field).resolvedType;
        if (
          target &&
          isType(target) &&
          !FIELD_TYPE_OVERRIDES[`${name}.${field.name}`]
        ) {
          dfs(target);
        }
      }
      if (this.regions.get(name) === block.objtype) {
        out.push(type);
      }
    };
    dfs(block.type);
    return out;
  }

  // --- field types ---------------------------------------------------------

  // FieldOpts (brewblox.proto) that deliberately have no effect on the
  // TypeScript type. Listed here so nobody mistakes them for forgotten ones:
  // - scale: the wire value is the number multiplied by scale; the service
  //   divides it out before the API, so the TS type stays `number`.
  // - logged / stored: read-mode filters in the service (which fields a
  //   logged or stored read returns); they never change a field's type.
  // - skip_changed: which fields a CHANGED read leaves out; it never changes
  //   a field's type.
  // - ignored (and nanopb FT_IGNORE): handled before this method is reached;
  //   such fields are filtered out in emittedFields().
  // Every other option (unit, objtype, readonly, datetime, hexed, hexstr,
  // ipv4address, bitfield, omit_if_zero, null_if_zero) is mapped below.
  fieldType(type, field) {
    const name = `${fq(type)}.${field.name}`;
    const opts = fieldOpts(field);
    let base;
    const override = FIELD_TYPE_OVERRIDES[name];
    if (override) {
      return { type: override, optional: false, opts };
    }
    const items = wrappedItems(field);
    if (items) {
      const list = this.fieldType(field.resolvedType, items).type;
      return {
        type: opts.readonly ? `Readonly<${list}>` : list,
        optional: false,
        opts,
      };
    }
    if (opts.objtype) {
      base = 'Link';
    } else if (opts.unit) {
      base = 'Quantity';
    } else if (opts.datetime) {
      base = 'DateString | null';
    } else if (opts.hexed || opts.hexstr || opts.ipv4address) {
      base = 'string';
    } else if (field.resolvedType && isEnum(field.resolvedType)) {
      base = this.enumName(field.resolvedType);
    } else if (field.resolvedType) {
      base = this.messageName(field.resolvedType);
    } else if (opts.bitfield) {
      base = BITFIELD_ENUMS[name] ?? 'number';
    } else if (field.type in SCALAR_TYPES) {
      base = SCALAR_TYPES[field.type];
      if (field.type === 'bytes') {
        warn(
          `${name}: bytes without hexstr is base64 on the wire; emitted as string`,
        );
      }
    } else {
      fail(`${name}: unsupported field type ${field.type}`);
    }

    // null_if_zero applies per element: the service converts a scalar
    // field's zero to null, and for a repeated field it converts each zero
    // element to null (`(T | null)[]`, not `T[] | null`). A unit or objtype
    // field is unaffected: the null lands inside Quantity.value / Link.id.
    let element = base;
    if (opts.null_if_zero && !opts.unit && !opts.objtype) {
      if (field.map) {
        fail(`${name}: null_if_zero on a map field has no codec rule`);
      }
      element = `${element} | null`;
    }

    let out = element;
    const union = element.includes('|');
    if (field.map) {
      if (field.keyType !== 'string') {
        fail(`${name}: only string map keys are supported`);
      }
      out = `{ [key: string]: ${element} }`;
    } else if (field.repeated) {
      out = union ? `(${element})[]` : `${element}[]`;
    }
    // A readonly field marked optional is absent while the block reports it
    // invalid, and the service sends null for it. A unit or objtype field
    // is unaffected: the null lands inside Quantity.value / Link.id.
    if (
      opts.readonly &&
      field.options?.proto3_optional &&
      !opts.unit &&
      !opts.objtype
    ) {
      out = `${out} | null`;
    }
    if (opts.readonly) {
      out = `Readonly<${out}>`;
    }

    let optional = false;
    if (opts.omit_if_zero && !field.repeated) {
      optional = true; // the service deletes the key when the value is 0
    }
    if (OPTIONAL_SUBMESSAGE_FIELDS.has(name)) {
      optional = true;
    }
    if (field.partOf && field.partOf.oneof.length > 1) {
      optional = true; // at most one member of the oneof is set
    }
    return { type: out, optional, opts };
  }

  // --- emission: messages --------------------------------------------------

  fieldLines(type) {
    const lines = [];
    let lastOneof = null;
    for (const field of this.emittedFields(type)) {
      const { type: tsType, optional } = this.fieldType(type, field);
      const oneof =
        field.partOf && field.partOf.oneof.length > 1 ? field.partOf : null;
      if (oneof && oneof !== lastOneof) {
        lines.push(`// oneof ${oneof.name}: at most one is set`);
      }
      lastOneof = oneof;
      const comment = field.comment ? field.comment.split('\n') : [];
      if (comment.length > 1) {
        lines.push(...comment.map((c) => `// ${c}`));
      }
      const trailing = comment.length === 1 ? ` // ${comment[0]}` : '';
      lines.push(`${field.name}${optional ? '?' : ''}: ${tsType};${trailing}`);
    }
    return lines;
  }

  emitMessage(type) {
    const name = fq(type);
    const tsName = this.messageName(type);
    const opts = msgOpts(type);
    if (ONEOF_UNION_MESSAGES.has(name)) {
      return this.emitUnionMessage(type);
    }
    if (opts.objtype) {
      return [
        `export interface ${tsName} extends Block {`,
        `type: '${opts.objtype}';`,
        'data: {',
        ...this.fieldLines(type),
        '};',
        '}',
      ].join('\n');
    }
    let extendsClause = '';
    if (EXTENDS[name]) {
      const base = this.messages.get(EXTENDS[name]);
      if (!base) {
        fail(`${name} extends ${EXTENDS[name]}, which is not reachable`);
      }
      this.assertExtends(type, base);
      extendsClause = ` extends ${this.messageName(base)}`;
    }
    return [
      `export interface ${tsName}${extendsClause} {`,
      ...this.fieldLines(type),
      '}',
    ].join('\n');
  }

  assertExtends(type, base) {
    for (const baseField of this.emittedFields(base)) {
      const field = type.fields[baseField.name];
      if (!field) {
        fail(
          `${fq(type)} cannot extend ${fq(base)}: missing field ${baseField.name}`,
        );
      }
      const a = stripReadonly(this.fieldType(base, baseField).type);
      const b = stripReadonly(this.fieldType(type, field).type);
      if (a !== b) {
        fail(
          `${fq(type)} cannot extend ${fq(base)}: ` +
            `${baseField.name} is ${b} but the base has ${a}`,
        );
      }
    }
  }

  emitUnionMessage(type) {
    const tsName = this.messageName(type);
    const fields = this.emittedFields(type);
    const oneofs = Object.values(type.oneofs ?? {}).filter(
      (o) => o.oneof.length > 1,
    );
    if (oneofs.length !== 1) {
      fail(
        `${fq(type)}: oneofStyle union needs exactly one multi-member oneof`,
      );
    }
    const [oneof] = oneofs;
    const common = fields
      .filter((f) => f.partOf !== oneof)
      .map((f) => {
        const { type: t, optional } = this.fieldType(type, f);
        return `${f.name}${optional ? '?' : ''}: ${t};`;
      });
    const members = fields
      .filter((f) => f.partOf === oneof)
      .map((f) => {
        const { type: t } = this.fieldType(type, f);
        return `| { ${[...common, `${f.name}: ${t};`].join(' ')} }`;
      });
    return [`export type ${tsName} =`, ...members, ';'].join('\n');
  }

  // --- emission: interface blocks ------------------------------------------

  implementors(intf) {
    const found = this.blocks
      .filter((b) => b.impl.includes(intf))
      .map((b) => b.type);
    for (const assumed of INTERFACE_BLOCKS[intf].assumedImplementors ?? []) {
      const type = this.messages.get(assumed);
      if (!type) {
        fail(
          `${intf}: assumed implementor ${assumed} is not a reachable Block`,
        );
      }
      if (!found.includes(type)) {
        found.push(type);
      }
    }
    return found;
  }

  emitInterfaceBlock(intf) {
    const config = INTERFACE_BLOCKS[intf];
    if (!config) {
      fail(`no INTERFACE_BLOCKS entry for ${intf}`);
    }
    if (!(intf in this.blockTypeEnum.values)) {
      fail(`${intf} is not a brewblox.BlockType value`);
    }
    const impls = this.implementors(intf);
    if (!impls.length) {
      fail(`${intf} has no implementors`);
    }
    const lines = [];
    for (const [fieldName, declared] of Object.entries(config.fields)) {
      const types = new Set();
      const stripped = new Set();
      for (const impl of impls) {
        const field = impl.fields[fieldName];
        if (!field || !this.emittedFields(impl).includes(field)) {
          fail(`${fq(impl)} implements ${intf} but has no field ${fieldName}`);
        }
        const { type, optional } = this.fieldType(impl, field);
        if (optional) {
          fail(`${fq(impl)}.${fieldName}: interface fields cannot be optional`);
        }
        types.add(type);
        stripped.add(stripReadonly(type));
      }
      let tsType = declared;
      if (!tsType) {
        if (types.size === 1) {
          [tsType] = types;
        } else if (stripped.size === 1) {
          [tsType] = stripped;
        } else {
          fail(
            `${intf}.${fieldName}: implementors disagree (${[...types].join(', ')}); ` +
              'declare the type in INTERFACE_BLOCKS',
          );
        }
      }
      lines.push(`${fieldName}: ${tsType};`);
    }
    return [
      `export interface ${intf}Block extends Block {`,
      'data: {',
      ...lines,
      '};',
      '}',
    ].join('\n');
  }

  // --- emission: files -----------------------------------------------------

  generateTypes(enumNames) {
    const regions = [];
    for (const shared of SHARED_REGIONS) {
      const parts = [];
      if (shared.prefix) {
        parts.push(shared.prefix);
      }
      for (const name of shared.messages ?? []) {
        parts.push(this.emitMessage(this.messages.get(name)));
      }
      for (const intf of shared.interfaces ?? []) {
        parts.push(this.emitInterfaceBlock(intf));
      }
      regions.push(region(shared.region, parts.join('\n\n')));
    }
    regions.push(DEPRECATED_CONSTRAINTS_FRAGMENT);

    const blockRegions = this.blocks.map((block) => ({
      name: block.objtype,
      body: this.blockRegionMessages(block)
        .map((type) => this.emitMessage(type))
        .join('\n\n'),
    }));
    for (const [name, body] of Object.entries(LEGACY_BLOCK_FRAGMENTS)) {
      if (blockRegions.some((r) => r.name === name)) {
        fail(`legacy block ${name} now has a proto message; drop the fragment`);
      }
      blockRegions.push({ name, body });
    }
    blockRegions.sort((a, b) => cmpName(a.name, b.name));
    for (const { name, body } of blockRegions) {
      regions.push(region(name, body));
    }

    // Unplaced reachable messages would be a generator bug.
    for (const name of this.messages.keys()) {
      if (!this.messageNames.has(name)) {
        fail(`${name} is reachable but was not emitted`);
      }
    }

    const body = [TYPES_PREAMBLE, ...regions].join('\n');
    const used = enumNames
      .filter((n) => new RegExp(`\\b${n}\\b`).test(body))
      .sort(cmpName);
    const imports = `import {\n${used.map((n) => `  ${n},`).join('\n')}\n} from './spark-block-enums';\n`;
    return `${HEADER}\n${imports}\n${body}`;
  }

  generateEnums() {
    const emitted = new Map(); // TS name -> { body, numeric }
    for (const [tsName, config] of Object.entries(NUMERIC_ENUMS)) {
      const enm = this.root.lookupEnum(config.source);
      emitted.set(tsName, {
        numeric: true,
        body: emitNumericEnum(tsName, enm, config),
      });
      this.enumNames.set(fq(enm), tsName);
    }
    for (const enm of this.enums.values()) {
      const tsName = this.enumName(enm);
      if (emitted.has(tsName)) {
        continue;
      }
      emitted.set(tsName, {
        numeric: false,
        body: emitStringEnum(tsName, enm),
      });
    }
    for (const [tsName, config] of Object.entries(VERBATIM_ENUMS)) {
      if (emitted.has(tsName)) {
        fail(
          `verbatim enum ${tsName} now has a proto source; drop the fragment`,
        );
      }
      emitted.set(tsName, config);
    }

    const regions = [];
    const placed = []; // TS names in file order
    for (const entry of ENUM_REGION_ORDER) {
      const [name, names] = Array.isArray(entry) ? entry : [entry, [entry]];
      const bodies = names.map((n) => {
        if (!emitted.has(n)) {
          fail(`ENUM_REGION_ORDER lists ${n}, which is not generated`);
        }
        placed.push(n);
        return emitted.get(n).body;
      });
      regions.push(region(name, bodies.join('\n')));
    }
    for (const [name, { body }] of emitted) {
      if (!placed.includes(name)) {
        placed.push(name);
        regions.push(region(name, body));
      }
    }

    const aliases = [
      ...ENUMS_CONSTANTS_ALIASES,
      ...placed.filter((n) => !emitted.get(n).numeric),
    ].map((n) => `export type ${n} = Enum<typeof ${n}>;`);

    const text = [
      HEADER,
      ENUMS_HEADER,
      region('BlockIntfType', this.emitBlockIntfType()),
      region('BlockType', this.emitBlockType()),
      ENUMS_CONSTANTS_FRAGMENT,
      ...regions,
      aliases.join('\n'),
    ].join('\n');
    return { text, names: [...emitted.keys(), ...ENUMS_CONSTANTS_ALIASES] };
  }

  emitBlockIntfType() {
    for (const name of BLOCK_INTF_TYPES) {
      const value = this.blockTypeEnum.values[name];
      if (value === undefined || value < 1 || value > 255) {
        fail(
          `BLOCK_INTF_TYPES: ${name} is not an interface value of brewblox.BlockType`,
        );
      }
    }
    return stringEnum('BlockIntfType', BLOCK_INTF_TYPES);
  }

  emitBlockType() {
    const objtypes = this.blocks.map((b) => b.objtype);
    for (const name of SYSTEM_BLOCK_TYPES) {
      if (!objtypes.includes(name) && !LEGACY_BLOCK_TYPES.includes(name)) {
        fail(`SYSTEM_BLOCK_TYPES: ${name} is not a Block objtype`);
      }
    }
    const user = [...objtypes, ...LEGACY_BLOCK_TYPES]
      .filter((n) => !SYSTEM_BLOCK_TYPES.includes(n))
      .sort(cmpName);
    return [
      stringEnum('SystemBlockType', SYSTEM_BLOCK_TYPES),
      stringEnum('UserBlockType', user),
      `export const BlockType = Enum(
  ...Enum.values(SystemBlockType),
  ...Enum.values(UserBlockType),
);
`,
    ].join('\n');
  }
}

// ---------------------------------------------------------------------------
// Emission helpers
// ---------------------------------------------------------------------------

function cmpName(a, b) {
  const la = a.toLowerCase();
  const lb = b.toLowerCase();
  return la < lb ? -1 : la > lb ? 1 : 0;
}

function stripReadonly(type) {
  const m = /^Readonly<(.*)>$/.exec(type);
  return m ? m[1] : type;
}

function region(name, body) {
  return `// #region ${name}\n${body.trim()}\n// #endregion ${name}\n`;
}

function stringEnum(name, members) {
  const lines = members.map((m) =>
    typeof m === 'string'
      ? `'${m}',`
      : `'${m.name}',${m.comment ? ` // ${m.comment}` : ''}`,
  );
  return `export const ${name} = Enum(\n${lines.join('\n')}\n);\n`;
}

function emitStringEnum(tsName, enm) {
  return stringEnum(tsName, enumMembers(enm));
}

function emitNumericEnum(tsName, enm, config) {
  const lines = enumMembers(enm).map(({ name, value, comment }) => {
    let member = name;
    if (config.stripPrefix) {
      if (!member.startsWith(config.stripPrefix)) {
        fail(`${fq(enm)}.${name} does not start with ${config.stripPrefix}`);
      }
      member = member.slice(config.stripPrefix.length);
    }
    member = config.rename?.[member] ?? member;
    const literal =
      value === 0
        ? '0'
        : Number.isInteger(Math.log2(value))
          ? `1 << ${Math.log2(value)}`
          : String(value);
    return `${member} = ${literal},${comment ? ` // ${comment}` : ''}`;
  });
  return `export enum ${tsName} {\n${lines.join('\n')}\n}\n`;
}

function regionNames(text) {
  return new Set([...text.matchAll(/^\/\/ #region (\S+)/gm)].map((m) => m[1]));
}

async function writeGenerated(file, text) {
  const filepath = path.join(tsDir, file);
  const config = (await prettier.resolveConfig(filepath)) ?? {};
  const formatted = await prettier.format(text, {
    ...config,
    parser: 'typescript',
  });
  if (fs.existsSync(filepath)) {
    const missing = [...regionNames(fs.readFileSync(filepath, 'utf8'))].filter(
      (name) => name && !regionNames(formatted).has(name),
    );
    if (missing.length && !allowRegionRemoval) {
      fail(
        `${file}: regions ${missing.join(', ')} would be removed; the docs site ` +
          'includes them. Pass --allow-region-removal if this is intended.',
      );
    }
  }
  fs.writeFileSync(filepath, formatted);
  console.log(`wrote ${path.relative(repoDir, filepath)}`);
}

async function main() {
  const root = await loadRoot();
  const gen = new Generator(root);
  gen.collect();
  gen.assignRegions();
  const enums = gen.generateEnums();
  const types = gen.generateTypes(enums.names);
  await writeGenerated('spark-block-enums.ts', enums.text);
  await writeGenerated('spark-block-types.ts', types);
  for (const w of warnings) {
    console.warn(`warning: ${w}`);
  }
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
