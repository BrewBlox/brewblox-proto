const fq = (obj) => obj.fullName.replace(/^\./, '');

function fail(msg) {
  throw new Error(msg);
}

const warnings = [];
function warn(msg) {
  warnings.push(msg);
}

// `.options` flattens repeated options to the last value; parsedOptions keeps
// every value.
function collectOptions(parsedOptions, key) {
  const out = {};
  for (const entry of parsedOptions ?? []) {
    if (entry[key]) {
      for (const [k, v] of Object.entries(entry[key])) {
        out[k] = k in out ? [].concat(out[k], v) : v;
      }
    }
  }
  return out;
}

function fieldOpts(field) {
  const opts = collectOptions(field.parsedOptions, '(brewblox.field)');
  const nanopb = collectOptions(field.parsedOptions, '(nanopb)');
  opts.ftIgnore = nanopb.type === 'FT_IGNORE';
  return opts;
}

function msgOpts(type) {
  const opts = collectOptions(type.parsedOptions, '(brewblox.msg)');
  opts.impl = [].concat(opts.impl ?? []);
  return opts;
}

function isType(obj) {
  return obj instanceof protobuf.Type;
}

function isEnum(obj) {
  return obj instanceof protobuf.Enum;
}

// A list wrapper is a message whose one field is the repeated or map field
// `items`. The service's API carries the list without the wrapper, so a field
// of a wrapper type takes the list's type; returns the `items` field, or null.
function wrappedItems(field) {
  const target = field.resolvedType;
  if (!target || !isType(target) || field.repeated || field.map) {
    return null;
  }
  const fields = target.fieldsArray;
  if (fields.length !== 1) {
    return null;
  }
  const [items] = fields;
  return items.name === 'items' && (items.repeated || items.map) ? items : null;
}

function* walk(ns) {
  for (const obj of Object.values(ns.nested ?? {})) {
    yield obj;
    if (obj.nested) {
      yield* walk(obj);
    }
  }
}

// First declared name for each value, in declaration order.
function enumMembers(enm) {
  const seen = new Set();
  const members = [];
  for (const [name, value] of Object.entries(enm.values)) {
    if (seen.has(value)) {
      continue;
    }
    seen.add(value);
    members.push({ name, value, comment: enm.comments?.[name] ?? null });
  }
  return members;
}

